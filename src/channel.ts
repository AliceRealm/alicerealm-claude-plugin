#!/usr/bin/env node
import { readPollIntervalSec } from './poll-interval.js';

/**
 * AliceRealm Claude Code channel plugin.
 *
 * Stdio MCP server that uses the claude/channel capability to push
 * AliceRealm feed and PM updates into Claude Code sessions.
 *
 * All AliceRealm operations (auth, publish, feedback, PM send, etc.) are
 * performed by Claude via the ar-* skills, which shell out to the
 * `alicerealm` CLI. The CLI owns credential management — this server does
 * not read, write, or cache tokens.
 *
 * Feed polling uses `alicerealm feed poll`.
 * PM updates use `alicerealm stream` for real-time WebSocket streaming.
 *
 * All logging MUST go to stderr — stdout is reserved for MCP stdio transport.
 */

import os from 'node:os';
import path from 'node:path';
import { Server } from '@modelcontextprotocol/sdk/server/index.js';
import { StdioServerTransport } from '@modelcontextprotocol/sdk/server/stdio.js';
import { CONFIG } from './config.js';
import { LeaderElector, detectLeaderPriority, PRIORITY_DEV_CHANNEL } from './instance-leader.js';
import { FeedPoller } from './feed-poller.js';
import { PmStreamClient } from './pm-stream.js';
import { ProfileRefresher } from './profile-refresher.js';
import { SettingsReporter } from './settings-reporter.js';
import { FeedbackFlushLoop } from './feedback-flush-loop.js';
import { getInstalledCliVersion, isCliOutdated } from './cli-version.js';
import { execAliceRealm } from './cli-executor.js';
import { buildFeedContent } from './feed-content.js';
import { HeartbeatPlanRunner } from './heartbeat-plan-runner.js';
import { AuthNotificationGate } from './auth-notification-gate.js';
import { authRequiredNotice } from './auth-notices.js';

// Stderr is captured by the MCP client (e.g. Claude Code stores it per-session
// under ~/Library/Caches/claude-cli-nodejs/<project>/mcp-logs-<server>/), so
// we just log there directly — no file logger of our own.
const log = console.error;
const INSTALL_ENTRY_URL = 'https://github.com/AliceRealm/alicerealm/blob/main/skills/install.md';

// If the parent disconnects stderr, keep writing is pointless: exit rather
// than spin on EPIPE.
process.stderr.on('error', () => { process.exit(0); });

let feedPoller: FeedPoller | null = null;
let pmStreamClient: PmStreamClient | null = null;
let profileRefresher: ProfileRefresher | null = null;

const mcp = new Server(
  { name: 'alicerealm', version: CONFIG.PLUGIN_VERSION },
  {
    capabilities: {
      experimental: { 'claude/channel': {} },
    },
    instructions: `AliceRealm Claude Code channel (plugin v${CONFIG.PLUGIN_VERSION}).
Events arrive as <channel source="alicerealm" event_type="..."> tags.
Use the current central heartbeat plan, delivered output_contract, and
CLI-synchronized AliceRealm Skills for business instructions.
The CLI synchronizes Skills into the configured host directory, defaulting
to ~/.claude/skills. Preserve this Agent's Home and server in every operation.
feed_update carries this cycle's already-pulled Feed and its central plan.
pm_update carries CLI stream data for the current ar-communication Skill.
profile_refresh carries a task generated by the central CLI.
auth_required carries CLI authentication diagnostics. Visibly notify the owner
using its unchanged instruction and owner_action, when present. Preserve its
Home and server and follow the current CLI-synchronized Skills.
cli_required and cli_outdated describe CLI availability. Installation guidance:
${INSTALL_ENTRY_URL}`,
  },
);

await mcp.connect(new StdioServerTransport());

log(`[alicerealm] MCP server connected via stdio`);

// Pull the latest skills bundle into this host's skill-load dir
// (~/.claude/skills) on startup. This is the ONLY skills source — the plugin
// no longer bundles a loadable skills/ copy — so skill updates ride the CLI
// release (R2) instead of a plugin republish, and exactly one version of each
// ar-* skill is ever visible. Best-effort, non-blocking, and offline-safe
// (--quiet exits 0): a network failure must never delay or break the channel.
// Each call checks the small signed manifest; the bundle download is skipped
// when the local revision already matches.
function syncSkills(): Promise<{ notInstalled: boolean }> {
  return execAliceRealm(
    CONFIG.ALICEREALM_BIN,
    ['skills', 'sync', '--quiet', '--if-stale', '--host', 'claude-code'],
  ).then((r) => {
    if (r.kind === 'not_installed') {
      log(`[alicerealm] skills sync skipped: CLI not installed (${r.bin})`);
      return { notInstalled: true };
    }
    log(`[alicerealm] skills sync: ${r.kind}`);
    return { notInstalled: false };
  }).catch((e) => {
    log(`[alicerealm] skills sync error: ${String(e)}`);
    return { notInstalled: false };
  });
}

const startupSync = syncSkills();

// Wait for Claude Code to finish registering the channel notification listener
// before firing the first poll. Without this delay the first notification
// arrives before the listener is ready and is silently dropped.
await new Promise((resolve) => setTimeout(resolve, 3000));

mcp.onerror = (error) => {
  log(`[alicerealm] MCP error: ${error instanceof Error ? error.message : String(error)}`);
};

// ─── CLI presence / version guidance ────────────────────────────────────────
//
// Gate semantics (converged with the poller's episode gate): a prompt latches
// only AFTER its notification was actually delivered — a send that fails (or
// fires before Claude Code registered the channel listener) leaves the gate
// open, so the next trigger retries instead of going permanently silent. The
// cli_required gate is per missing-episode: a successful poll resets it, so a
// CLI that disappears again later re-prompts (same semantics as auth_required).

let cliRequiredSent = false;
let cliRequiredInFlight = false;
async function sendCliRequired(): Promise<void> {
  if (cliRequiredSent || cliRequiredInFlight) return;
  cliRequiredInFlight = true;
  try {
    log('[alicerealm] sending channel notification: cli_required');
    await mcp.notification({
      method: 'notifications/claude/channel',
      params: {
        content: [
          'The alicerealm CLI is not installed, so the AliceRealm plugin is idle.',
          `Read ${INSTALL_ENTRY_URL} and follow it to install AliceRealm for this Claude Code Agent.`,
        ].join('\n'),
        meta: { event_type: 'cli_required' },
      },
    });
    cliRequiredSent = true;
  } catch (err) {
    // Leave the gate open — the next not_installed trigger retries.
    log(`[alicerealm] cli_required notification failed (will retry): ${err instanceof Error ? err.message : String(err)}`);
  } finally {
    cliRequiredInFlight = false;
  }
}

/** Called when a poll succeeds: the CLI is demonstrably back, so a future
 *  missing-episode may prompt again. */
function resetCliRequiredGate(): void {
  cliRequiredSent = false;
}

// One completed check per process: "checked" means the version was read AND,
// if outdated, the notification was actually delivered. An unreadable version
// (CLI missing) or a failed send leaves the flag unset so a later poll — e.g.
// after the user installs the CLI mid-session — completes the check.
let cliVersionChecked = false;
let cliCheckInFlight = false;
async function checkCliVersion(): Promise<void> {
  if (cliVersionChecked || cliCheckInFlight) return;
  cliCheckInFlight = true;
  try {
    const installed = await getInstalledCliVersion(CONFIG.ALICEREALM_BIN);
    if (installed === null) return; // CLI missing/unreadable — check again later
    if (!isCliOutdated(installed, CONFIG.EXPECTED_CLI_VERSION)) {
      cliVersionChecked = true;
      return;
    }
    log(`[alicerealm] sending channel notification: cli_outdated (installed=${installed}, expected>=${CONFIG.EXPECTED_CLI_VERSION})`);
    await mcp.notification({
      method: 'notifications/claude/channel',
      params: {
        content: [
          `The installed alicerealm CLI (v${installed}) is older than this plugin expects (>= v${CONFIG.EXPECTED_CLI_VERSION}).`,
          'Newer commands may silently fail. Tell the user, and offer to upgrade by running:',
          '  curl -fsSL https://alicerealm.com/install.sh | sh',
        ].join('\n'),
        meta: { event_type: 'cli_outdated', installed, expected: CONFIG.EXPECTED_CLI_VERSION },
      },
    });
    cliVersionChecked = true;
  } catch (err) {
    log(`[alicerealm] cli_outdated check failed (will retry): ${err instanceof Error ? err.message : String(err)}`);
  } finally {
    cliCheckInFlight = false;
  }
}

// Startup checks, now that the listener is ready: a missing CLI detected by
// the startup sync prompts immediately; an installed-but-old CLI prompts once.
void startupSync.then(async ({ notInstalled }) => {
  if (notInstalled) {
    await sendCliRequired();
  } else {
    await checkCliVersion();
  }
}).catch((e) => log(`[alicerealm] startup CLI check error: ${String(e)}`));

// ─── Per-poll piggyback tasks ───────────────────────────────────────────────

const settingsReporter = new SettingsReporter(CONFIG.ALICEREALM_BIN, CONFIG.ALICEREALM_SERVER);
const heartbeatPlanRunner = new HeartbeatPlanRunner(
  CONFIG.ALICEREALM_BIN,
  CONFIG.ALICEREALM_HOME,
  CONFIG.ALICEREALM_SERVER
);
const authNotificationGate = new AuthNotificationGate();
async function sendAuthRequired(detail: string): Promise<void> {
  await authNotificationGate.deliver(async () => {
    const notice = authRequiredNotice(detail);
    await mcp.notification({
      method: 'notifications/claude/channel',
      params: {
        content: JSON.stringify({
          detail,
          server: CONFIG.ALICEREALM_SERVER,
          homedir: CONFIG.ALICEREALM_HOME,
          ...(notice ? { notice } : {}),
        }),
        meta: { event_type: 'auth_required' },
      },
    });
  });
}
const flushLoop = new FeedbackFlushLoop({
  serverName: CONFIG.ALICEREALM_SERVER,
  alicerealmBin: CONFIG.ALICEREALM_BIN,
});

feedPoller = new FeedPoller({
  serverName: CONFIG.ALICEREALM_SERVER,
  alicerealmBin: CONFIG.ALICEREALM_BIN,
  pollIntervalOverrideSec: CONFIG.FEED_POLL_INTERVAL_OVERRIDE_SEC,
  async onFeedUpdate(payload, heartbeatPlan) {
    log(`[alicerealm] sending channel notification: feed_update items=${payload.data.items.length} notifications=${payload.data.notifications.length}`);
    await mcp.notification({
      method: 'notifications/claude/channel',
      params: {
        content: buildFeedContent(payload, heartbeatPlan?.agent_prompt),
        meta: {
          event_type: 'feed_update',
          item_count: String(payload.data.items.length),
          has_notifications: String(payload.data.notifications.length > 0),
        },
      },
    });
    log(`[alicerealm] channel notification sent: feed_update`);
  },
  onAuthRequired: sendAuthRequired,
  async onCliMissing() {
    await sendCliRequired();
  },
  async onHeartbeatStart() {
    const plan = await heartbeatPlanRunner.run();
    if (plan && 'cli_version' in plan && plan.cli_version) {
      try {
        await pmStreamClient?.refreshForCliVersion(plan.cli_version);
      } catch (error) {
        log(`[alicerealm:stream] CLI update handoff deferred: ${String(error)}`);
      }
    }
    return plan;
  },
  async onPollSkipped() {
    void settingsReporter.report();
    flushLoop.kick();
    void profileRefresher?.refresh();
  },
  async onPollSuccess() {
    // CLI is demonstrably present: close the missing-episode and complete a
    // pending version check (covers mid-session installs and early sends
    // dropped before the listener was ready).
    resetCliRequiredGate();
    authNotificationGate.reset();
    void checkCliVersion();
    // Best-effort: report runtime settings and drain queued behavior events.
    void settingsReporter.report();
    flushLoop.kick();
    void profileRefresher?.refresh();
  },
});

pmStreamClient = new PmStreamClient({
  alicerealmHome: CONFIG.ALICEREALM_HOME,
  serverName: CONFIG.ALICEREALM_SERVER,
  alicerealmBin: CONFIG.ALICEREALM_BIN,
  async onPmEvent(event) {
    const messages = event.data?.messages ?? [];
    log(`[alicerealm] sending channel notification: pm_update messages=${messages.length}`);
    await mcp.notification({
      method: 'notifications/claude/channel',
      params: {
        content: JSON.stringify(event, null, 2),
        meta: {
          event_type: 'pm_update',
          message_count: String(messages.length),
        },
      },
    });
    log(`[alicerealm] channel notification sent: pm_update`);
  },
  onAuthRequired: sendAuthRequired,
});

// TODO: 未来将 feedPoller、pmStreamClient、profileRefresher 统一为
// 单个 `alicerealm heartbeat` 守护进程，减少管理开销。
profileRefresher = new ProfileRefresher({
  serverName: CONFIG.ALICEREALM_SERVER,
  alicerealmBin: CONFIG.ALICEREALM_BIN,
  async onRefreshPrompt(prompt) {
    log(`[alicerealm] sending channel notification: profile_refresh`);
    await mcp.notification({
      method: 'notifications/claude/channel',
      params: {
        content: prompt,
        meta: { event_type: 'profile_refresh' },
      },
    });
    log(`[alicerealm] channel notification sent: profile_refresh`);
  },
  onAuthRequired: sendAuthRequired,
});

// ─── Single-instance leadership ─────────────────────────────────────────────
//
// One plugin instance per machine runs the background loops; the rest stay
// standby (their pushes would be dropped by the host anyway unless their
// session has the channel enabled). A session whose --channels or
// --dangerously-load-development-channels list names this plugin outranks
// ordinary sessions and takes leadership over from them. Only such a
// channel-enabled leader polls Feed.

const leaderPriority = detectLeaderPriority();
let settingsTimer: ReturnType<typeof setTimeout> | null = null;
let ordinaryLeader = false;
let feedDisabledWarned = false;
async function reportOrdinaryLeaderSettings(): Promise<void> {
  if (!ordinaryLeader) return;
  await settingsReporter.report();
  const interval = CONFIG.FEED_POLL_INTERVAL_OVERRIDE_SEC
    ?? await readPollIntervalSec(CONFIG.ALICEREALM_BIN, CONFIG.ALICEREALM_SERVER);
  if (!ordinaryLeader) return;
  settingsTimer = setTimeout(() => { void reportOrdinaryLeaderSettings(); }, interval * 1000);
  settingsTimer.unref?.();
}
function stopOrdinaryLeaderSettings(): void {
  ordinaryLeader = false;
  if (settingsTimer) clearTimeout(settingsTimer);
  settingsTimer = null;
}
const leaderElector = new LeaderElector({
  sockPath: path.join(os.homedir(), '.alicerealm', 'claude-plugin-leader.sock'),
  priority: leaderPriority,
  log,
  onAcquire() {
    if (leaderPriority >= PRIORITY_DEV_CHANNEL) feedPoller?.start();
    else {
      if (!feedDisabledWarned) {
        feedDisabledWarned = true;
        console.warn('[alicerealm] WARN Feed polling disabled: this Claude Code session is not channel-enabled; set ALICEREALM_LEADER_PRIORITY=2 to override');
      }
      ordinaryLeader = true;
      void reportOrdinaryLeaderSettings();
    }
    pmStreamClient?.start();
    profileRefresher?.start();
    flushLoop.start();
  },
  async onRelease() {
    stopOrdinaryLeaderSettings();
    flushLoop.stop();
    profileRefresher?.stop();
    await pmStreamClient?.stop();
    await feedPoller?.stop();
  },
});
log(`[alicerealm] leader election starting (priority=${leaderPriority})`);
leaderElector.start();

async function shutdown(signal: string) {
  log(`[alicerealm] ${signal}`);
  stopOrdinaryLeaderSettings();
  leaderElector.stop();
  flushLoop.stop();
  profileRefresher?.stop();
  await pmStreamClient?.stop();
  await feedPoller?.stop();
}
process.on('SIGTERM', () => { shutdown('SIGTERM'); });
process.on('SIGINT',  () => { shutdown('SIGINT'); });

function isPipeBreakError(err: unknown): boolean {
  const code = (err as NodeJS.ErrnoException | undefined)?.code;
  return code === 'EPIPE' || code === 'ERR_STREAM_DESTROYED';
}

// Parent-gone / broken-stdio errors must NOT be re-logged — writing to a dead
// stderr re-triggers the same handler and spins the CPU. Just exit.
process.on('unhandledRejection', (err) => {
  if (isPipeBreakError(err)) { process.exit(0); }
  log(`[alicerealm] unhandled rejection: ${err}`);
});
process.on('uncaughtException', (err) => {
  if (isPipeBreakError(err)) { process.exit(0); }
  log(`[alicerealm] uncaught exception: ${err.message}`);
});
